/** A record with one entry per key. */
function each<K extends string>(keys: readonly K[], text: (key: K) => string): Record<K, string> {
  const out = {} as Record<K, string>;
  for (const key of keys) out[key] = text(key);
  return out;
}

const plural = (unit: string): Plural => ({ one: `{count} ${unit}`, few: `{count} ${unit}s`, many: `{count} ${unit}s`, other: `{count} ${unit}s` });

